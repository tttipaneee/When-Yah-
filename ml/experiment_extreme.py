"""Experiment: does the with_level model understate drops when the price is far above normal? -> reports/extreme_experiment.md

Problem seen: at level ~2 the model gives ~36% chance of a >= 10% drop by +30 min, while train/test data show
57-72% (few windows). Candidate fix: let trees fit smaller groups (min_child_samples 200 -> 50) and force
the drop probability to rise / the expected ratio to fall monotonically with `level`.

Pre-registered rule (written before running): KEEP the fix only if, on TEST days at +30 min,
 (1) calibration error |mean predicted - observed drop rate| for level >= 1.5 is smaller than the current model's, AND
 (2) overall ROC-AUC does not drop by more than 0.005.
Usage: python -m ml.experiment_extreme
"""
from datetime import date
from pathlib import Path

import joblib
import lightgbm as lgb
import numpy as np
import pandas as pd
from sklearn.metrics import roc_auc_score

from ml.features import WITH_LEVEL
from ml.train import MODEL, PARAMS, load_frame

ROOT = Path(__file__).resolve().parent.parent
REPORT = ROOT / "reports" / "extreme_experiment.md"
FIX = {**PARAMS, "min_child_samples": 50}
MONO_CLF = [1 if f == "level" else 0 for f in WITH_LEVEL]   # higher level -> higher drop chance


def calib(df: pd.DataFrame, p: np.ndarray, mask: np.ndarray) -> tuple[int, float, float]:
    return int(mask.sum()), float(p[mask].mean()), float(df.drop10_30.to_numpy()[mask].mean())


def main() -> None:
    df = load_frame()
    tr = df[(df.split == "train") & df.drop10_30.notna()]
    te = df[(df.split == "test") & df.drop10_30.notna()].reset_index(drop=True)
    cur = joblib.load(MODEL)["models"]["with_level"][30]["clf"]
    new = lgb.LGBMClassifier(**FIX, monotone_constraints=MONO_CLF).fit(tr[WITH_LEVEL], tr.drop10_30.astype(int))
    y = te.drop10_30.astype(int).to_numpy()
    ps = {"current": cur.predict_proba(te[WITH_LEVEL])[:, 1], "fix": new.predict_proba(te[WITH_LEVEL])[:, 1]}
    lvl = te.level.to_numpy()
    bands = [("all", np.ones(len(te), bool)), ("level < 1.2", lvl < 1.2), ("1.2 ≤ level < 1.5", (lvl >= 1.2) & (lvl < 1.5)),
             ("level ≥ 1.5", lvl >= 1.5), ("level ≥ 1.8", lvl >= 1.8)]
    L = ["# Experiment: drop chance when the price is far above normal", "",
         f"Generated by `python -m ml.experiment_extreme` on {date.today().isoformat()}. +30 min, test days (Aug 26–31).",
         "Fix = min_child_samples 50 + drop chance monotone increasing in level. Rule (pre-registered): keep only if",
         "calibration error for level ≥ 1.5 shrinks AND overall AUC drops ≤ 0.005.", "",
         "| Windows | n | Observed drop rate | Current: mean predicted | Fix: mean predicted |", "|---|---|---|---|---|"]
    err = {}
    for name, m in bands:
        n, pc, obs = calib(te, ps["current"], m)
        _, pf, _ = calib(te, ps["fix"], m)
        L.append(f"| {name} | {n:,} | {obs:.1%} | {pc:.1%} | {pf:.1%} |")
        if name == "level ≥ 1.5":
            err = {"current": abs(pc - obs), "fix": abs(pf - obs)}
    auc = {k: roc_auc_score(y, p) for k, p in ps.items()}
    keep = err["fix"] < err["current"] and auc["fix"] >= auc["current"] - 0.005
    L += ["", f"- Calibration error, level ≥ 1.5: current {err['current']:.1%}, fix {err['fix']:.1%}",
          f"- Overall AUC: current {auc['current']:.3f}, fix {auc['fix']:.3f}", "",
          f"**Result: {'KEEP the fix' if keep else 'do NOT keep the fix'}** under the pre-registered rule."]
    REPORT.write_text("\n".join(L) + "\n", encoding="utf-8")
    print("\n".join(L))


if __name__ == "__main__":
    main()
