"""Is the route-based normal-fare estimate accurate enough? -> reports/fare_check.md + reports/fare_check.json

Compares api.fare.raw_fare(route) with REAL off-peak Grab prices we saw ourselves
(data/fares/offpeak_quotes.csv: when seen, from/to coordinates, price), for two ways to get km/minutes:
 - osrm:   OpenStreetMap routing, free-flow (empty-road) minutes;
 - tomtom: TomTom traffic-aware minutes (needs TOMTOM_API_KEY). TomTom cannot be asked about past times,
           so each quote uses the SAME weekday and time one week after it was seen (typical traffic for that slot).
Gate per method (fixed in code before any quotes were added):
 - raw estimate passes if median |error| <= 15%;
 - else, if errors are steady (all quotes within ±15% of the median ratio), a correction factor =
   median(real / estimate) is allowed (fitted on our own real quotes, documented) — needs >= 4 quotes;
 - otherwise FAIL. The served method is tomtom if it passed, else osrm if it passed, else none (users type
   the usual price).
Usage: python -m ml.fare_check
"""
import json
from datetime import date, datetime, timedelta
from pathlib import Path

import pandas as pd

from api.fare import CACHE, _key, raw_fare, route
from api.traffic import route_with_traffic

ROOT = Path(__file__).resolve().parent.parent
QUOTES = ROOT / "data" / "fares" / "offpeak_quotes.csv"
REPORT, SUMMARY = ROOT / "reports" / "fare_check.md", ROOT / "reports" / "fare_check.json"


def gate(d: pd.DataFrame) -> tuple[bool, float, str, float, float, bool]:
    err = (d.estimate / d.real - 1).abs()
    med = float(d.ratio.median())
    steady = bool(((d.ratio / med - 1).abs() <= 0.15).all())
    if float(err.median()) <= 0.15:
        return True, 1.0, "PASS (raw estimate)", float(err.median()), med, steady
    if steady and len(d) >= 4:
        return True, med, f"PASS with correction factor ×{med:.2f} (fitted on our own real quotes)", \
            float(err.median()), med, steady
    return False, 1.0, "FAIL — errors too large or not steady", float(err.median()), med, steady


def main() -> None:
    q = pd.read_csv(QUOTES)
    q = q[(q.app == "grab") & ~q.note.fillna("").str.startswith("EXCLUDED")]  # off-peak prices only
    cache = json.loads(CACHE.read_text()) if CACHE.exists() else {}
    rows = {"osrm": [], "tomtom": []}
    for _, r in q.iterrows():
        a, b = (r.from_lat, r.from_lon), (r.to_lat, r.to_lon)
        name = f"{r.from_name} → {r.to_name}"
        rt = route(a, b, timeout=15)
        if rt is not None:
            cache[_key(a, b)] = list(rt)
            rows["osrm"].append(dict(route=name, seen_at=r.seen_at, km=rt[0], min=rt[1], real=r.price_rm))
        seen = datetime.fromisoformat(r.seen_at)
        nxt = seen + timedelta(days=7)
        while nxt <= datetime.now(seen.tzinfo) + timedelta(minutes=5):  # TomTom needs a future departure
            nxt += timedelta(days=7)
        tt = route_with_traffic(a, b, nxt, timeout=15)
        if tt is not None:
            rows["tomtom"].append(dict(route=name, seen_at=r.seen_at, km=tt[0], min=tt[1], real=r.price_rm,
                                       asked_for=nxt.strftime("%a %d %b %H:%M")))
    CACHE.write_text(json.dumps(cache, indent=1))

    L = ["# Fare check — route-based normal Grab fare vs real off-peak quotes", "",
         f"Generated by `python -m ml.fare_check` on {date.today().isoformat()}. Rates: `data/fares/grab_rates.csv`",
         "(Grab Klang Valley, Jan 2023); real prices: `data/fares/offpeak_quotes.csv` (seen by us in the Grab app).", ""]
    result = {}
    for method, label in [("osrm", "OpenStreetMap, empty-road minutes"),
                          ("tomtom", "TomTom traffic-aware minutes (same weekday/time, one week later)")]:
        d = pd.DataFrame(rows[method])
        L += [f"## {method}: {label}", ""]
        if d.empty:
            L += ["Not available (no route data" + (" — set TOMTOM_API_KEY" if method == "tomtom" else "") + ").", ""]
            continue
        d["estimate"] = [raw_fare(k, m) for k, m in zip(d["km"], d["min"])]
        d["ratio"] = d.real / d.estimate
        ok, factor, verdict, med_err, med, steady = gate(d)
        result[method] = dict(passed=ok, factor=round(factor, 3), n_quotes=int(len(d)), median_abs_error=round(med_err, 3))
        L += ["| Route | Seen at | km | min | Real RM | Estimate RM | Real ÷ estimate |", "|---|---|---|---|---|---|---|"]
        L += [f"| {r.route} | {r.seen_at} | {r.km:.1f} | {getattr(r, "min"):.0f} | {r.real:.2f} | {r.estimate:.2f} | {r.ratio:.2f} |"
              for r in d.itertuples()]
        L += ["", f"- Median |error| of raw estimate: {med_err:.0%}; median real ÷ estimate: {med:.2f}; steady (all within "
              f"±15% of median): {steady}; quotes: {len(d)}", "", f"**{method}: {verdict}.**", ""]
    served = next((m for m in ("tomtom", "osrm") if result.get(m, {}).get("passed")), None)
    L += [f"**Served: {served or 'none — the app keeps asking for the usual price'}.**"]
    SUMMARY.write_text(json.dumps({"passed": served is not None, "method": served,
                                   "factor": result.get(served, {}).get("factor", 1.0), "methods": result}, indent=1))
    REPORT.write_text("\n".join(L) + "\n", encoding="utf-8")
    print("\n".join(L))


if __name__ == "__main__":
    main()
