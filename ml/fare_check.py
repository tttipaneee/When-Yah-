"""Is the route-based normal-fare estimate accurate enough? -> reports/fare_check.md + reports/fare_check.json

Compares api.fare.raw_fare(OSRM route) with REAL off-peak Grab prices we saw ourselves
(data/fares/offpeak_quotes.csv: when seen, from/to coordinates, price). Gate (fixed in code before any quotes were added):
 - raw estimate passes if median |error| <= 15%;
 - else, if errors are steady (all quotes within ±15% of the median ratio), a correction factor =
   median(real / estimate) is allowed (fitted on our own real quotes, documented) — needs >= 4 quotes;
 - otherwise FAIL: the app keeps the typed "usual price".
Usage: python -m ml.fare_check
"""
import json
from datetime import date
from pathlib import Path

import numpy as np
import pandas as pd

from api.fare import CACHE, _key, raw_fare, route

ROOT = Path(__file__).resolve().parent.parent
QUOTES = ROOT / "data" / "fares" / "offpeak_quotes.csv"
REPORT, SUMMARY = ROOT / "reports" / "fare_check.md", ROOT / "reports" / "fare_check.json"


def main() -> None:
    q = pd.read_csv(QUOTES)
    q = q[(q.app == "grab") & ~q.note.fillna("").str.startswith("EXCLUDED")]  # off-peak prices only
    cache = json.loads(CACHE.read_text()) if CACHE.exists() else {}
    rows = []
    for _, r in q.iterrows():
        a, b = (r.from_lat, r.from_lon), (r.to_lat, r.to_lon)
        rt = route(a, b, timeout=15)
        if rt is None:
            continue
        cache[_key(a, b)] = list(rt)
        est = raw_fare(*rt)
        rows.append(dict(route=f"{r.from_name} → {r.to_name}", seen_at=r.seen_at, km=rt[0], min=rt[1],
                         real=r.price_rm, estimate=est, ratio=r.price_rm / est))
    CACHE.write_text(json.dumps(cache, indent=1))
    d = pd.DataFrame(rows)
    L = ["# Fare check — route-based normal Grab fare vs real off-peak quotes", "",
         f"Generated by `python -m ml.fare_check` on {date.today().isoformat()}. Rates: `data/fares/grab_rates.csv`;",
         "routes: OpenStreetMap (OSRM); real prices: `data/fares/offpeak_quotes.csv` (seen by us in the Grab app).", ""]
    passed, factor = False, 1.0
    if len(d) == 0:
        L += ["**No real quotes yet → FAIL (not enough data).** The app keeps the typed usual price."]
    else:
        err = (d.estimate / d.real - 1).abs()
        med_ratio = float(d.ratio.median())
        steady = bool(((d.ratio / med_ratio - 1).abs() <= 0.15).all())
        if float(err.median()) <= 0.15:
            passed, verdict = True, "PASS (raw estimate)"
        elif steady and len(d) >= 4:
            passed, factor = True, med_ratio
            verdict = f"PASS with correction factor ×{med_ratio:.2f} (fitted on our own real quotes)"
        else:
            verdict = "FAIL — errors too large or not steady; the app keeps the typed usual price"
        L += ["| Route | Seen at | km | min (free-flow) | Real RM | Estimate RM | Real ÷ estimate |", "|---|---|---|---|---|---|---|"]
        L += [f"| {r.route} | {r.seen_at} | {r.km:.1f} | {r.min:.0f} | {r.real:.2f} | {r.estimate:.2f} | {r.ratio:.2f} |"
              for r in d.itertuples()]
        L += ["", f"- Median |error| of raw estimate: {err.median():.0%}; median real ÷ estimate: {med_ratio:.2f};"
              f" steady (all within ±15% of median): {steady}; quotes: {len(d)}", "", f"**Result: {verdict}.**"]
    SUMMARY.write_text(json.dumps({"passed": passed, "factor": round(factor, 3), "n_quotes": int(len(d))}, indent=1))
    REPORT.write_text("\n".join(L) + "\n", encoding="utf-8")
    print("\n".join(L))


if __name__ == "__main__":
    main()
