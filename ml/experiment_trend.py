"""Experiment: does a second quote ~15 min earlier (price trend) make the forecast useful? -> reports/trend_experiment.md

Serving idea: the user types the price now and the price they saw ~15 min ago (same app).
Training analogue: trend = idx_a(t) / idx_a(t-15) — same zone, previous window, trip-half A only, so it
shares no sampling noise with the outcome (measured on half B, as in evaluate.py).

Rule (fixed in code before the run; committed together with the results): the trend helps if, on held-out TEST days, a
trend variant's mean policy saving has a 95% CI lower bound above the hour-of-day baseline's upper bound,
OR its +30 min drop-10% AUC is >= 0.03 above with_level's. Otherwise: report "trend does not help".
All policies are scored on the same test rows (those where the previous window exists).
Usage: python -m ml.experiment_trend
"""
from datetime import date
from pathlib import Path

import joblib
import lightgbm as lgb
import numpy as np
import pandas as pd
from sklearn.metrics import roc_auc_score

from ml.evaluate import decide, pct, policy_stats
from ml.features import HORIZONS, NO_LEVEL, WITH_LEVEL
from ml.train import MODEL, PARAMS, drop_prob, load_frame

ROOT = Path(__file__).resolve().parent.parent
REPORT = ROOT / "reports" / "trend_experiment.md"
VARIANTS = {"trend_only": NO_LEVEL + ["trend"], "level_trend": WITH_LEVEL + ["trend"]}


def add_trend(df: pd.DataFrame) -> pd.DataFrame:
    key = df.set_index(["zone", "bucket"])
    prev = pd.MultiIndex.from_arrays([df.zone, df.bucket - pd.Timedelta(minutes=15)])
    same_split = key.split.reindex(prev).to_numpy() == df.split.to_numpy()
    df["trend"] = np.where(same_split, df.idx_a.to_numpy() / key.idx_a.reindex(prev).to_numpy(), np.nan)
    return df


def main() -> None:
    df = add_trend(load_frame())
    rcols = [f"ratio_{h}" for h in HORIZONS]
    tr = df[(df.split == "train") & df.trend.notna()]
    te = df[(df.split == "test") & df.trend.notna()].dropna(subset=rcols).reset_index(drop=True)
    actual = te[rcols].to_numpy()
    clusters = (te.zone.astype(str) + "_" + te.bucket.dt.date.astype(str)).to_numpy()
    print(f"train rows with trend: {len(tr):,}; test rows: {len(te):,}")

    base = joblib.load(MODEL)
    preds = {}
    for v, feats in base["features"].items():
        ms = base["models"][v]
        preds[v] = {k: np.c_[[ms[h][k].predict(te[feats]) for h in HORIZONS]].T for k in ("mean", "q90")}
        preds[v]["p30"] = drop_prob(ms[30], te[feats])
    for v, feats in VARIANTS.items():
        preds[v] = {"mean": [], "q90": []}
        for h in HORIZONS:
            d = tr[tr[f"ratio_{h}"].notna()]
            X, y = d[feats], d[f"ratio_{h}"]
            preds[v]["mean"].append(lgb.LGBMRegressor(**PARAMS).fit(X, y).predict(te[feats]))
            preds[v]["q90"].append(lgb.LGBMRegressor(objective="quantile", alpha=0.9, **PARAMS)
                                   .fit(X, y).predict(te[feats]))
            if h == 30:
                preds[v]["p30"] = lgb.LGBMClassifier(**PARAMS).fit(X, d["drop10_30"].astype(int)) \
                    .predict_proba(te[feats])[:, 1]
        preds[v] = {k: (np.c_[val].T if k != "p30" else val) for k, val in preds[v].items()}
        print(f"trained {v}")

    hour_avg = {h: tr.groupby("hour")[f"ratio_{h}"].mean() for h in HORIZONS}
    ha = np.c_[[te.hour.map(hour_avg[h]).to_numpy() for h in HORIZONS]].T
    rows = {"Book now (always)": policy_stats(np.zeros(len(te), bool), np.zeros(len(te), int), actual, clusters),
            "Hour-of-day average ratio": policy_stats(*decide(ha, None), actual, clusters)}
    for v in preds:
        rows[f"When Yah? {v}"] = policy_stats(*decide(preds[v]["mean"], preds[v]["q90"]), actual, clusters)
    y30 = (actual[:, 1] <= 0.9).astype(int)
    auc = {v: roc_auc_score(y30, preds[v]["p30"]) for v in preds}
    mae = {v: np.abs(actual[:, 1] - preds[v]["mean"][:, 1]).mean() / np.abs(actual[:, 1] - 1).mean() - 1
           for v in preds}

    ho = rows["Hour-of-day average ratio"]
    wins = [v for v in VARIANTS if rows[f"When Yah? {v}"]["lo"] > ho["hi"] or auc[v] >= auc["with_level"] + 0.03]
    L = ["# Experiment: second quote (price trend)", "",
         f"Generated by `python -m ml.experiment_trend` on {date.today().isoformat()}. Same data, splits and",
         "noise control as `reports/metrics.md`; trend = price now ÷ price 15 min earlier (trip-half A).",
         f"Test windows with a previous window and all horizons: **{len(te):,}**.",
         "Rule (fixed in code before the run): trend helps if a trend variant's saving CI is above the hour-of-day baseline's,",
         "or its +30 min drop AUC is ≥ 0.03 above with_level's.", "",
         "| Policy | Waits | Mean saving vs book now (95% CI) | Saving when it waits | Waits that cost more | AUC drop ≥10% @30 | MAE @30 vs persistence |",
         "|---|---|---|---|---|---|---|"]
    for k, s in rows.items():
        v = k.replace("When Yah? ", "")
        extra = f"{auc[v]:.3f} | {mae[v]:+.1%}" if v in auc else "– | –"
        L.append(f"| {k} | {s['wait_rate']:.1%} | {pct(s['saving'])} ({pct(s['lo'])} … {pct(s['hi'])}) | "
                 f"{pct(s['saving_when_wait'])} | {s['worse_share_of_waits']:.1%} | {extra} |")
    L += ["", f"**Result: {'trend HELPS (' + ', '.join(wins) + ')' if wins else 'trend does NOT help'}** "
          "under the rule (fixed in code before the run)."]
    REPORT.write_text("\n".join(L) + "\n", encoding="utf-8")
    print("\n".join(L))


if __name__ == "__main__":
    main()
